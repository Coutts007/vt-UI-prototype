export const useTailorText = () => {
  const { locale } = useI18n();
  return (key: TailorKey, params: Record<string, string | number> = {}) =>
    Object.entries(params).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      (locale === 'sw' ? tailorSw : tailorEn)[key] as string,
    );
};
