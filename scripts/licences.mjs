#!/usr/bin/env node
// Writes docs/LICENSES.md from the production dependencies and fails on a prohibited licence (NFR-14).
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const run = (cmd) => execSync(cmd, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

const rows = [];
const web = JSON.parse(run('pnpm --filter @vt/web licenses list --prod --json'));
for (const [licence, packages] of Object.entries(web)) {
  for (const pkg of packages) {
    for (const version of pkg.versions ?? [pkg.version]) {
      rows.push(['web', pkg.name, version, licence]);
    }
  }
}
const api = JSON.parse(
  run('uv run --quiet --no-dev --with pip-licenses pip-licenses --format=json --from=mixed'),
);
for (const pkg of api) {
  if (['pip-licenses', 'prettytable', 'wcwidth', 'tomli'].includes(pkg.Name)) continue;
  rows.push(['api', pkg.Name, pkg.Version, pkg.License]);
}
rows.sort((a, b) => a[0].localeCompare(b[0]) || a[1].localeCompare(b[1]));

// LGPL is allowed only as an unmodified dynamically linked library, so it is reviewed, not blocked.
const prohibited = /(^|[^L])(A?GPL)|non-?commercial|CC[- ]BY-NC/i;
const bad = rows.filter((r) => prohibited.test(r[3]));

const table = rows.map((r) => `| ${r.join(' | ')} |`).join('\n');
writeFileSync(
  'docs/LICENSES.md',
  `# Deployed dependency licences\n\nGenerated by \`make licences\`. Do not edit.\n\n| Tier | Package | Version | Licence |\n|---|---|---|---|\n${table}\n`,
);
console.log(`${rows.length} deployed packages written to docs/LICENSES.md`);
if (bad.length) {
  console.error('Prohibited licences:\n' + bad.map((r) => r.join(' ')).join('\n'));
  process.exit(1);
}
